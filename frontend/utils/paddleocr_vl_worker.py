# Discrepancy & Validation Checker
# -------------------------------------------------------------------------

def audit_discrepancies(summary: Dict[str, Any], line_items: List[Dict[str, Any]]) -> Dict[str, Any]:
    printed_grand_total = summary.get("grand_total")
    round_off = summary.get("round_off")
    rec_round_off = summary.get("recognized_round_off", round_off)
    derived_ro = summary.get("derived_round_off")
    sign_source = summary.get("round_off_sign_source", "recognized")

    sum_line_taxable = sum([it["taxable_amount"] for it in line_items if it.get("taxable_amount") is not None])
    sum_line_total = sum([it["total"] for it in line_items if it.get("total") is not None])

    base_sum = sum_line_total if (len(line_items) > 0 and sum_line_total > 0) else (
        (summary.get("subtotal") or 0.0) + (summary.get("total_tax") or ((summary.get("cgst_amount") or 0.0) + (summary.get("sgst_amount") or 0.0) + (summary.get("igst_amount") or 0.0)) or 0.0)
    )

    notes = []
    discrepancy_amount = 0.0
    status = "Reconciled"

    if printed_grand_total is not None and base_sum > 0:
        diff = round(base_sum - printed_grand_total, 2)
        required_adjustment = round(printed_grand_total - base_sum, 2)
        discrepancy_amount = diff

        if abs(diff) == 0.0:
            status = "Exact Match"
        elif abs(diff) <= 0.05:
            status = "Minor Rounding Variance (Preserved)"
            notes.append(
                f"Line item gross sum ({base_sum:,.2f}) differs by {diff:+.2f} from printed grand total "
                f"({printed_grand_total:,.2f}) due to per-item tax rounding. Printed grand total is preserved."
            )
        elif round_off is not None and abs(abs(round_off) - abs(required_adjustment)) <= 0.05:
            status = "Reconciled with Round-Off"
            discrepancy_amount = required_adjustment
            if sign_source == "ambiguous_label":
                notes.append(
                    f"Line item sum ({base_sum:,.2f}) reconciles with printed total ({printed_grand_total:,.2f}) "
                    f"via mathematically derived round-off adjustment ({required_adjustment:+.2f}). "
                    f"Printed round-off magnitude: {abs(round_off):.2f} (Ambiguous sign in print: (+/-))."
                )
            else:
                notes.append(
                    f"Line item sum ({base_sum:,.2f}) reconciles with printed total ({printed_grand_total:,.2f}) "
                    f"via round-off adjustment ({required_adjustment:+.2f})."
                )
        else:
            status = "Discrepancy Detected"
            notes.append(
                f"Discrepancy of {diff:+.2f} between sum of line items ({base_sum:,.2f}) and printed total ({printed_grand_total:,.2f})."
            )

    return {
        "status": status,
        "discrepancy_amount": discrepancy_amount,
        "derived_adjustment": derived_ro or (discrepancy_amount if "Round-Off" in status else None),
        "recognized_round_off": rec_round_off,
        "round_off_sign_source": sign_source,
        "sum_line_taxable": round(sum_line_taxable, 2) if sum_line_taxable else None,
        "sum_line_total": round(sum_line_total, 2) if sum_line_total else None,
        "notes": notes
    }


