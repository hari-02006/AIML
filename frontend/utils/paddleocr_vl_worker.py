class HTMLTableExtractor(HTMLParser):
    def __init__(self):
        super().__init__()
        self.tables = []
        self._curr_table = []
        self._curr_row = []
        self._curr_cell = []
        self._curr_attrs = {}
        self._in_cell = False

    def handle_starttag(self, tag, attrs):
        if tag == 'table':
            self._curr_table = []
        elif tag == 'tr':
            self._curr_row = []
        elif tag in ('td', 'th'):
            self._curr_cell = []
            self._curr_attrs = dict(attrs)
            self._in_cell = True

    def handle_endtag(self, tag):
        if tag in ('td', 'th'):
            self._in_cell = False
            cell_text = ''.join(self._curr_cell).strip()
            colspan = int(self._curr_attrs.get('colspan', 1))
            self._curr_row.append(cell_text)
            # For colspan > 1, expand so subsequent column indexing remains consistent
            for _ in range(colspan - 1):
                self._curr_row.append('')
        elif tag == 'tr':
            if self._curr_row:
                self._curr_table.append(self._curr_row)
        elif tag == 'table':
            if self._curr_table:
                self.tables.append(self._curr_table)

    def handle_data(self, data):
        if self._in_cell:
            self._curr_cell.append(data)


def clean_amount(val_str: Any, allow_negative: bool = False) -> Optional[float]:
    if val_str is None:
        return None
    raw = str(val_str).strip()
    is_negative = allow_negative and ("-" in raw)
    s = re.sub(r"[^\d,\. ]", "", raw).strip().replace(" ", "")
    if not s:
        return None
    if "," in s and "." in s:
        if s.rfind(",") > s.rfind("."):
            s = s.replace(".", "").replace(",", ".")
        else:
            s = s.replace(",", "")
    elif "," in s:
        parts = s.split(",")
        if len(parts) == 2 and len(parts[1]) in (1, 2):
            s = parts[0] + "." + parts[1]
        else:
            s = s.replace(",", "")
    try:
        val = float(s)
        if is_negative:
            return -abs(val)
        return val if (allow_negative or val >= 0) else 0.0
    except (ValueError, TypeError):
        return None


