GSTIN_PATTERN = re.compile(r"\b\d{2}[A-Z]{4,5}[A-Z0-9X]{8,9}\b")
DATE_PATTERNS = [
    re.compile(r"\b(\d{1,2}[-/\.]\d{1,2}[-/\.]\d{2,4})\b"),
    re.compile(r"\b(\d{1,2}[-/\.](?:Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)[a-z]*[-/\.]\d{2,4})\b", re.IGNORECASE),
    re.compile(r"\b(\d{1,2}\s+(?:Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)[a-z]*\s+\d{2,4})\b", re.IGNORECASE),
    re.compile(r"\b((?:Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)[a-z]*\s+\d{1,2},?\s+\d{2,4})\b", re.IGNORECASE),
]

def extract_metadata_from_markdown(markdown_text: str, tables: List[List[List[str]]], raw_text: str = "") -> Dict[str, Any]:
    meta = {
        "invoice_number": None,
        "invoice_date": None,
        "due_date": None,
        "seller_name": None,
        "buyer_name": None,
        "seller_tax_id": None,
        "buyer_tax_id": None,
        "seller_gstin": None,
        "buyer_gstin": None,
        "currency": "Unknown",
        "payment_mode": None,
        "uncertain_fields": []
    }

    combined_search_text = markdown_text + "\n" + raw_text

    if "₹" in combined_search_text or "INR" in combined_search_text or "GST" in combined_search_text or "Rupees" in combined_search_text:
        meta["currency"] = "INR"
    elif "$" in combined_search_text or "USD" in combined_search_text:
        meta["currency"] = "USD"
    elif "€" in combined_search_text or "EUR" in combined_search_text:
        meta["currency"] = "EUR"
    elif "£" in combined_search_text or "GBP" in combined_search_text:
        meta["currency"] = "GBP"

    gstins = GSTIN_PATTERN.findall(combined_search_text.upper())
    if gstins:
        meta["seller_gstin"] = gstins[0]
        if len(gstins) > 1:
            meta["buyer_gstin"] = gstins[1]

    for table in tables:
        for row in table:
            row_str = " ".join([c for c in row if c])
            low_str = row_str.lower()

            if any(k in low_str for k in ['inv. no', 'invoice no', 'inv no', 'bill no']):
                for idx, c in enumerate(row):
                    if any(k in c.lower() for k in ['inv. no', 'invoice no', 'inv no', 'bill no']):
                        cand = next((cell.strip(" :#") for cell in row[idx + 1:] if cell.strip(" :#")), None)
                        if cand and len(cand) >= 2:
                            meta["invoice_number"] = cand

            if any(k in low_str for k in ['inv. date', 'invoice date', 'date of issue', 'bill date', 'date:']):
                for idx, c in enumerate(row):
                    if any(k in c.lower() for k in ['inv. date', 'invoice date', 'date of issue', 'bill date', 'date:']):
                        cand = next((cell.strip() for cell in row[idx + 1:] if cell.strip() and not any(w in cell.lower() for w in ['terms', 'delivery'])), "")
                        for dp in DATE_PATTERNS:
                            m = dp.search(cand)
                            if m:
                                meta["invoice_date"] = m.group(1)
                                break

            if 'payment mode' in low_str:
                for idx, c in enumerate(row):
                    if 'payment mode' in c.lower():
                        cand = next((cell.strip() for cell in row[idx + 1:] if cell.strip() and not any(w in cell.lower() for w in ['reverse', 'charge'])), "")
                        if cand:
                            meta["payment_mode"] = cand

            if any(k in low_str for k in ['billed to', 'name :', 'name:']) and not meta["buyer_name"]:
                for idx, c in enumerate(row):
                    if 'name' in c.lower() and not any(b in c.lower() for b in ['bank', 'our']) and not meta["buyer_name"]:
                        if ':' in c:
                            cand = c.split(':', 1)[1].strip()
                        else:
                            cand = next((cell.strip(" :#") for cell in row[idx + 1:] if cell.strip(" :#")), None)
                        if cand and len(cand) >= 2:
                            meta["buyer_name"] = cand

            if any(k in low_str for k in ['gstin :', 'gstin:']):
                for idx, c in enumerate(row):
                    if 'gstin' in c.lower() and not any(b in c.lower() for b in ['bank', 'our']):
                        if ':' in c:
                            cand = c.split(':', 1)[1].strip()
                        else:
                            cand = next((cell.strip() for cell in row[idx + 1:] if cell.strip() and not any(w in cell.lower() for w in ['terms', 'delivery'])), None)
                        if cand and len(cand) >= 10:
                            meta["buyer_gstin"] = cand

    seller_m = re.search(r"##\s*(?:Seller|Supplier|Vendor):\s*\n+([^\n#]+)", combined_search_text, re.IGNORECASE)
    if seller_m and not meta["seller_name"]:
        meta["seller_name"] = seller_m.group(1).strip()

    client_m = re.search(r"##\s*(?:Client|Buyer|Customer|Bill\s*To):\s*\n+([^\n#]+)", combined_search_text, re.IGNORECASE)
    if client_m and not meta["buyer_name"]:
        meta["buyer_name"] = client_m.group(1).strip()

    gstin_header_m = re.search(r"##\s*(?:GSTIN\s*:[0-9A-Z]+\s+)?([A-Za-z0-9\s\-\&]+Shop|[A-Za-z0-9\s\-\&]+Ltd|[A-Za-z0-9\s\-\&]+Inc|[A-Za-z0-9\s\-\&]+Enterprises?|[A-Za-z0-9\s\-\&]+Store)", combined_search_text, re.IGNORECASE)
    if gstin_header_m and not meta["seller_name"]:
        cand = gstin_header_m.group(1).strip()
        cand = re.sub(r"^GSTIN\s*:[0-9A-Za-z]+\s*", "", cand).strip()
        if cand:
            meta["seller_name"] = cand

    if not meta["invoice_number"]:
        inv_m = re.search(r"(?:Invoice\s*(?:no|number|#)|Bill\s*(?:no|#)|Inv\s*no)[.:\s-]*([A-Za-z0-9\-\/]+)", combined_search_text, re.IGNORECASE)
        if inv_m:
            meta["invoice_number"] = inv_m.group(1).strip()

    tax_ids = re.findall(r"Tax\s*Id:\s*([0-9\-\/A-Za-z]+)", combined_search_text, re.IGNORECASE)
    if tax_ids:
        meta["seller_tax_id"] = tax_ids[0].strip()
        if len(tax_ids) > 1:
            meta["buyer_tax_id"] = tax_ids[1].strip()

    if not meta["invoice_date"]:
        date_issue_m = re.search(r"(?:Date\s*of\s*issue|Invoice\s*Date|Bill\s*Date)[.:\s\n]*(\d{1,2}[-/\.]\d{1,2}[-/\.]\d{2,4})", combined_search_text, re.IGNORECASE)
        if date_issue_m:
            meta["invoice_date"] = date_issue_m.group(1).strip()
        else:
            for dp in DATE_PATTERNS:
                dm = dp.search(combined_search_text)
                if dm:
                    meta["invoice_date"] = dm.group(1).strip()
                    break

    return meta


