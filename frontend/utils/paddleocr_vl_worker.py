_PIPELINE = None

def get_pipeline():
    global _PIPELINE
    if _PIPELINE is None:
        sys.stderr.write("[PaddleOCR-VL Worker] Initializing PaddleOCRVL(pipeline_version='v1.6')...\n")
        sys.stderr.flush()
        from paddleocr import PaddleOCRVL
        _PIPELINE = PaddleOCRVL(pipeline_version='v1.6')
        sys.stderr.write("[PaddleOCR-VL Worker] Initialization complete.\n")
        sys.stderr.flush()
    return _PIPELINE


def process_document(file_input: Any, filename: Optional[str] = None, pipeline: Any = None) -> Dict[str, Any]:
    """
    Renders single or multi-page documents (PDF, TIFF, JPG, PNG)
    and executes PaddleOCR-VL 1.6 inference. Supports pipeline injection for testing.
    """
    if pipeline is None:
        pipeline = get_pipeline()

    # Convert input to PIL image list
    pages: List[Image.Image] = []
    file_bytes = None

    if isinstance(file_input, bytes):
        file_bytes = file_input
    elif isinstance(file_input, str) and os.path.exists(file_input):
        with open(file_input, "rb") as f:
            file_bytes = f.read()
        if not filename:
            filename = os.path.basename(file_input)

    if not file_bytes:
        return {"success": False, "error": "No document content provided."}

    ext = os.path.splitext(filename or "image.png")[1].lower()

    # 1. Multi-page PDF
    if ext == ".pdf" or file_bytes.startswith(b"%PDF"):
        try:
            import pypdfium2 as pdfium
            pdf = pdfium.PdfDocument(file_bytes)
            for page_idx in range(len(pdf)):
                page = pdf[page_idx]
                pil_img = page.render(scale=2.0).to_pil().convert("RGB")
                pages.append(pil_img)
        except Exception as e:
            return {"success": False, "error": f"Failed to render PDF: {str(e)}"}

    # 2. TIFF (single or multi-frame)
    elif ext in [".tiff", ".tif"]:
        try:
            img = Image.open(io.BytesIO(file_bytes))
            n_frames = getattr(img, "n_frames", 1)
            for frame in range(n_frames):
                img.seek(frame)
                pages.append(img.copy().convert("RGB"))
        except Exception as e:
            return {"success": False, "error": f"Failed to read TIFF: {str(e)}"}

    # 3. Standard single image (JPG, PNG)
    else:
        try:
            img = Image.open(io.BytesIO(file_bytes)).convert("RGB")
            pages.append(img)
        except Exception as e:
            return {"success": False, "error": f"Failed to open image: {str(e)}"}

    if not pages:
        return {"success": False, "error": "No readable pages found in document."}

    all_line_items = []
    all_summary = {}
    combined_markdown = []
    combined_raw_text = []
    page_results = []
    all_tables = []

    # Run inference per page
    for p_idx, page_img in enumerate(pages):
        page_num = p_idx + 1
        max_dim = int(os.environ.get("PADDLE_MAX_IMAGE_SIZE", "1000"))
        if max(page_img.width, page_img.height) > max_dim:
            scale = float(max_dim) / max(page_img.width, page_img.height)
            page_img = page_img.resize((int(page_img.width * scale), int(page_img.height * scale)), Image.Resampling.LANCZOS)
        img_np = np.array(page_img)
        try:
            output = pipeline.predict(img_np)
        except Exception as exc:
            return {
                "success": False,
                "engine": "PaddleOCR-VL 1.6 (Local VLM)",
                "error": f"Failed to process page {page_num} of {len(pages)}: {str(exc)}",
                "failed_page": page_num,
                "total_pages": len(pages)
            }

        page_markdown = ""
        page_blocks = []
        page_lines = []

        for res in output:
            if hasattr(res, 'markdown') and isinstance(res.markdown, dict):
                md_texts = res.markdown.get('markdown_texts', '')
                page_markdown += md_texts + "\n\n"
            elif isinstance(res, dict) and 'markdown' in res:
                page_markdown += str(res['markdown']) + "\n\n"

            # Parse layout blocks
            parsing_list = res.get('parsing_res_list', []) if hasattr(res, 'get') else []
            for b in parsing_list:
                content = getattr(b, 'content', '') or ''
                label = getattr(b, 'label', '') or ''
                bbox = getattr(b, 'bbox', []) or []
                if content.strip():
                    page_blocks.append({
                        'label': label,
                        'content': content.strip(),
                        'bbox': bbox
                    })
                    page_lines.append(content.strip())

        # Extract items and summaries from page markdown HTML tables
        items, sum_data, tables = extract_tables_and_items(page_markdown, page_num=page_num)
        all_line_items.extend(items)
        all_tables.extend(tables)

        for k, v in sum_data.items():
            if v is not None and k not in all_summary:
                all_summary[k] = v

        combined_markdown.append(f"# Page {page_num}\n\n" + page_markdown)
        combined_raw_text.extend(page_lines)

        page_results.append({
            "page_number": page_num,
            "width": page_img.width,
            "height": page_img.height,
            "word_count": len(" ".join(page_lines).split()),
            "line_count": len(page_lines),
            "markdown": page_markdown,
            "blocks": page_blocks,
            "items_count": len(items)
        })

    full_markdown_text = "\n\n".join(combined_markdown)
    full_raw_text = "\n".join(combined_raw_text)

    # Extract high-level metadata
    metadata = extract_metadata_from_markdown(full_markdown_text, all_tables, raw_text=full_raw_text)

    # Reconcile discrepancies
    audit = audit_discrepancies(all_summary, all_line_items)

    return {
        "success": True,
        "engine": "PaddleOCR-VL 1.6 (Local VLM)",
        "page_count": len(pages),
        "total_words": len(full_raw_text.split()),
        "total_lines": len(combined_raw_text),
        "pages": page_results,
        "raw_text": full_raw_text,
        "lines": combined_raw_text,
        "layout_lines": combined_raw_text,
        "markdown": full_markdown_text,
        "metadata": metadata,
        "summary": all_summary,
        "line_items": all_line_items,
        "reconciliation": audit,
        "error": None
    }


