def extract_tables_and_items(html_text: str, page_num: int = 1) -> Tuple[List[Dict[str, Any]], Dict[str, Any], List[List[List[str]]]]:
    """
    Parses HTML tables generated by PaddleOCR-VL 1.6.
    Extracts line items and structured summary fields.
    """
    extractor = HTMLTableExtractor()
    extractor.feed(html_text)
    tables = extractor.tables

    items = []
    summary_data = {}

    for table in tables:
        header_row_idx = None
        col_map = {}

        # 1. Look for product items header
        for r_idx, row in enumerate(table):
            matches = 0
            curr_map = {}
            for c_idx, cell in enumerate(row):
                clow = cell.lower().strip()
                # Serial number column
                if clow in ['sn', 'no.', 's.no', 'sr.no', 'sl.no', 'sl no']:
                    curr_map['sn'] = c_idx
                    matches += 1
                # Product name / description headings
                elif any(k in clow for k in [
                    'description', 'discripion', 'product', 'product name', 
                    'item', 'item name', 'particular', 'particulars', 
                    'goods description', 'material description', 'goods', 'material'
                ]):
                    curr_map['desc'] = c_idx
                    matches += 1
                # Quantity headings
                elif any(k in clow for k in ['quantity', 'qty', 'count', 'pcs', 'pieces', 'nos']):
                    curr_map['qty'] = c_idx
                    matches += 1
                elif clow in ['units', 'unit', 'uom', 'um']:
                    if 'qty' not in curr_map:
                        curr_map['qty'] = c_idx
                    else:
                        curr_map['unit'] = c_idx
                    matches += 1
                elif 'hsn' in clow or 'sac' in clow:
                    curr_map['hsn'] = c_idx
                    matches += 1
                elif any(k in clow for k in ['gst rate', 'tax rate', 'vat rate', 'gst %', 'vat %', 'tax %']) or (any(k in clow for k in ['gst', 'tax', 'vat']) and '%' in clow):
                    curr_map['tax_rate'] = c_idx
                    matches += 1
                elif any(k in clow for k in ['unit price', 'unit rate', 'net price', 'price/unit', 'rate/item', 'price', 'rate']):
                    if not any(k in clow for k in ['gst', 'tax', 'vat']):
                        curr_map['rate'] = c_idx
                        matches += 1
                elif any(k in clow for k in ['taxable', 'net worth']):
                    curr_map['taxable'] = c_idx
                    matches += 1
                elif any(k in clow for k in ['gross worth', 'gross amount', 'line total', 'total']):
                    curr_map['total'] = c_idx
                    matches += 1
                elif any(k in clow for k in ['vat', 'gst', 'tax']):
                    curr_map['tax_amt'] = c_idx
                    matches += 1

            if matches >= 3 and 'desc' in curr_map:
                header_row_idx = r_idx
                col_map = curr_map

                # Check if next row has subheaders (% / Amt.)
                if r_idx + 1 < len(table):
                    next_low = [c.lower() for c in table[r_idx + 1]]
                    if any(c in ['%', 'amt.', 'amount'] for c in next_low):
                        if len(next_low) < len(row):
                            gst_base = curr_map.get('tax_rate') or curr_map.get('tax_amt')
                            if gst_base is None:
                                gst_base = curr_map.get('taxable', 5) + 1
                            for c_idx, cell in enumerate(next_low):
                                if cell == '%':
                                    col_map['tax_rate'] = gst_base + c_idx
                                elif cell in ['amt.', 'amount']:
                                    col_map['tax_amt'] = gst_base + c_idx
                        else:
                            for c_idx, cell in enumerate(next_low):
                                if cell == '%':
                                    col_map['tax_rate'] = c_idx
                                elif cell in ['amt.', 'amount']:
                                    col_map['tax_amt'] = c_idx
                        header_row_idx = r_idx + 1
                break

        # Extract items if header was located
        if header_row_idx is not None and 'desc' in col_map:
            for r_idx in range(header_row_idx + 1, len(table)):
                row = table[r_idx]
                row_str = " ".join([c for c in row if c]).lower()

                # Stop when reaching footer rows
                if any(k in row_str for k in ['sub-total', 'subtotal', 'total amount', 'bank details', 'summery', 'summary', 'our bank']):
                    break

                desc_idx = col_map.get('desc')
                desc = row[desc_idx] if desc_idx is not None and desc_idx < len(row) else ''
                if not desc or desc.isdigit() or len(desc.strip()) < 2:
                    continue

                raw_qty_cell = row[col_map['qty']].strip() if 'qty' in col_map and col_map['qty'] < len(row) else ''
                raw_unit_cell = row[col_map['unit']].strip() if 'unit' in col_map and col_map['unit'] < len(row) else ''

                qty = clean_amount(raw_qty_cell) if raw_qty_cell else None
                unit = None

                # Extract unit from quantity cell if present (e.g. "2 boxes", "5 pairs", "12 pcs")
                m_u = re.search(r"[a-zA-Z]+", raw_qty_cell)
                if m_u:
                    unit = m_u.group(0).strip()
                elif raw_unit_cell and not raw_unit_cell.isdigit():
                    unit = raw_unit_cell

                is_uncertain = False
                uncertain_reason = None
                if qty is None:
                    is_uncertain = True
                    uncertain_reason = "Quantity could not be recognized"
                elif qty <= 0:
                    is_uncertain = True
                    uncertain_reason = "Quantity is zero or negative"

                if qty is not None:
                    formatted_qty = int(qty) if isinstance(qty, float) and qty.is_integer() else qty
                    if unit and unit.lower() not in ['each', 'none', 'units', 'unit', '']:
                        quantity_str = f"{formatted_qty} {unit}"
                    elif unit and unit.lower() in ['units', 'unit']:
                        quantity_str = f"{formatted_qty} Units"
                    else:
                        quantity_str = str(formatted_qty)
                else:
                    quantity_str = "(Uncertain)"

                rate = clean_amount(row[col_map['rate']]) if 'rate' in col_map and col_map['rate'] < len(row) else None
                taxable = clean_amount(row[col_map['taxable']]) if 'taxable' in col_map and col_map['taxable'] < len(row) else None
                tax_rate = row[col_map['tax_rate']] if 'tax_rate' in col_map and col_map['tax_rate'] < len(row) else None
                tax_amt = clean_amount(row[col_map['tax_amt']]) if 'tax_amt' in col_map and col_map['tax_amt'] < len(row) else None

                # For total: use explicit total column or last column
                total = None
                if 'total' in col_map and col_map['total'] < len(row):
                    total = clean_amount(row[col_map['total']])
                if total is None and len(row) > 0:
                    total = clean_amount(row[-1])

                clean_desc = desc.strip()
                item = {
                    'item_num': len(items) + 1,
                    'product_name': clean_desc,
                    'description': clean_desc,
                    'quantity': qty if qty is not None else 1.0,
                    'quantity_str': quantity_str,
                    'unit': unit or (raw_unit_cell if raw_unit_cell else 'each'),
                    'is_uncertain': is_uncertain,
                    'uncertain_reason': uncertain_reason,
                    'hsn_sac': row[col_map['hsn']].strip() if 'hsn' in col_map and col_map['hsn'] < len(row) and row[col_map['hsn']].strip() else None,
                    'unit_price': rate,
                    'taxable_amount': taxable if taxable is not None else (rate * qty if rate and qty else None),
                    'tax_rate': tax_rate.strip() if tax_rate else None,
                    'tax_amount': tax_amt,
                    'total': total,
                    'page': page_num
                }
                items.append(item)

        # 2. Extract summary fields from table
        is_items_table = ('desc' in col_map and header_row_idx is not None)
        item_row_indices = set(range(header_row_idx + 1, header_row_idx + 1 + len(items))) if is_items_table else set()

        for r_idx, row in enumerate(table):
            # Skip header rows and product items
            if is_items_table and r_idx in item_row_indices:
                continue

            row_str = " ".join([c for c in row if c]).lower()

            # CGST & SGST (adjacent / non-empty cell aware)
            for idx, c in enumerate(row):
                clow = c.lower()
                if 'cgst' in clow:
                    cand_tokens = [c] + [tok for tok in row[idx + 1:] if tok.strip()]
                    nums = [clean_amount(tok) for tok in cand_tokens if clean_amount(tok) is not None]
                    if nums and 'cgst_amount' not in summary_data:
                        summary_data['cgst_amount'] = nums[-1]
                elif 'sgst' in clow:
                    cand_tokens = [c] + [tok for tok in row[idx + 1:] if tok.strip()]
                    nums = [clean_amount(tok) for tok in cand_tokens if clean_amount(tok) is not None]
                    if nums and 'sgst_amount' not in summary_data:
                        summary_data['sgst_amount'] = nums[-1]
                elif 'igst' in clow:
                    cand_tokens = [c] + [tok for tok in row[idx + 1:] if tok.strip()]
                    nums = [clean_amount(tok) for tok in cand_tokens if clean_amount(tok) is not None]
                    if nums and 'igst_amount' not in summary_data:
                        summary_data['igst_amount'] = nums[-1]
                elif 'round off' in clow or 'round-off' in clow:
                    label_text = c.strip()
                    cand_tokens = [c] + [tok for tok in row[idx + 1:] if tok.strip()]
                    nums = []
                    val_tok = ""
                    for tok in cand_tokens:
                        amt = clean_amount(tok, allow_negative=True)
                        if amt is not None:
                            nums.append(amt)
                            val_tok = tok
                    if nums and 'round_off' not in summary_data:
                        raw_num = nums[-1]
                        magnitude = abs(raw_num)
                        has_explicit_neg_in_val = "-" in val_tok and not any(amb in val_tok for amb in ["(+/-)", "+/-", "(±)"])
                        has_explicit_neg_in_label = "(-)" in clow or "less" in clow
                        has_ambiguous_sign = any(amb in clow for amb in ["(+/-)", "+/-", "(±)"])

                        if has_explicit_neg_in_val or has_explicit_neg_in_label:
                            recognized_val = -magnitude
                            sign_src = "explicit_negative"
                        elif has_ambiguous_sign:
                            recognized_val = magnitude
                            sign_src = "ambiguous_label"
                        else:
                            recognized_val = raw_num
                            sign_src = "unsigned_magnitude"

                        summary_data['round_off'] = recognized_val
                        summary_data['recognized_round_off'] = recognized_val
                        summary_data['round_off_sign_source'] = sign_src
                        summary_data['round_off_label'] = label_text

            if any(k in row_str for k in ['total amount', 'grand total', 'total payable']) and 'sub-total' not in row_str:
                for c in reversed(row):
                    amt = clean_amount(c)
                    if amt and amt > 0:
                        summary_data['grand_total'] = amt
                        break

            if 'sub-total' in row_str or 'subtotal' in row_str:
                nums = [clean_amount(c) for c in row if clean_amount(c) is not None]
                if nums and 'subtotal' not in summary_data:
                    if len(nums) >= 3:
                        summary_data['subtotal'] = nums[1]
                        summary_data['taxable_value'] = nums[1]
                        summary_data['total_tax'] = nums[2]
                        if 'grand_total' not in summary_data:
                            summary_data['grand_total'] = nums[3]
                    elif len(nums) == 1:
                        summary_data['subtotal'] = nums[0]

            # European summary table: [VAT [%], Net worth, VAT, Gross worth]
            if not is_items_table:
                if 'total' in row_str and any(c in row_str for c in ['$', '€', '£', ',', '.']):
                    nums = [clean_amount(c) for c in row if clean_amount(c) is not None]
                    if len(nums) >= 3 and 'grand_total' not in summary_data:
                        summary_data['subtotal'] = nums[0]
                        summary_data['taxable_value'] = nums[0]
                        summary_data['total_tax'] = nums[1]
                        summary_data['vat_amount'] = nums[1]
                        summary_data['grand_total'] = nums[2]
                elif any(c.endswith('%') for c in row):
                    vat_rate_val = next((c for c in row if '%' in c), None)
                    if vat_rate_val and 'vat_rate' not in summary_data:
                        summary_data['vat_rate'] = vat_rate_val
                    nums = [clean_amount(c) for c in row if clean_amount(c) is not None and '%' not in c]
                    if len(nums) >= 3 and 'grand_total' not in summary_data:
                        summary_data['subtotal'] = nums[0]
                        summary_data['taxable_value'] = nums[0]
                        summary_data['vat_amount'] = nums[1]
                        summary_data['total_tax'] = nums[1]
                        summary_data['grand_total'] = nums[2]

            # Bank details extraction
            if 'bank name' in row_str:
                for idx, c in enumerate(row):
                    if 'bank name' in c.lower():
                        cand = c.split(':', 1)[1].strip() if (':' in c and c.split(':', 1)[1].strip()) else next((cell.strip() for cell in row[idx + 1:] if cell.strip()), '')
                        if cand:
                            summary_data['bank_name'] = cand
            if 'account no' in row_str:
                for idx, c in enumerate(row):
                    if 'account no' in c.lower():
                        cand = c.split(':', 1)[1].strip() if (':' in c and c.split(':', 1)[1].strip()) else next((cell.strip() for cell in row[idx + 1:] if cell.strip()), '')
                        if cand:
                            summary_data['bank_account_no'] = cand
            if 'ifsc' in row_str:
                for idx, c in enumerate(row):
                    if 'ifsc' in c.lower():
                        cand = c.split(':', 1)[1].strip() if (':' in c and c.split(':', 1)[1].strip()) else next((cell.strip() for cell in row[idx + 1:] if cell.strip()), '')
                        if cand:
                            summary_data['bank_ifsc'] = cand

    # Determine derived round-off adjustment needed for mathematical reconciliation
    if summary_data.get('round_off') is not None:
        ro_val = summary_data['round_off']
        sum_items = sum([it['total'] for it in items if it.get('total') is not None]) if items else None
        gt = summary_data.get('grand_total')
        sub = summary_data.get('subtotal')
        tot_tax = summary_data.get('total_tax') or (
            (summary_data.get('cgst_amount') or 0.0) + (summary_data.get('sgst_amount') or 0.0) + (summary_data.get('igst_amount') or 0.0)
        )
        pre_tax = (sub + tot_tax) if (sub is not None and tot_tax is not None) else sub
        base_sum = sum_items if sum_items is not None else pre_tax

        if base_sum is not None and gt is not None:
            expected_diff = round(gt - base_sum, 2)
            if abs(abs(ro_val) - abs(expected_diff)) <= 0.05:
                summary_data['derived_round_off'] = expected_diff

    return items, summary_data, tables


