class PaddleOCRRequestHandler(BaseHTTPRequestHandler):
    def log_message(self, format, *args):
        sys.stderr.write(f"[PaddleOCR-VL Server] {format % args}\n")
        sys.stderr.flush()

    def do_GET(self):
        if self.path == "/health":
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.end_headers()
            cuda_available = False
            device = "cpu"
            device_name = "CPU"
            try:
                import paddle
                cuda_available = bool(paddle.device.is_compiled_with_cuda() and paddle.device.cuda.device_count() > 0)
                device = paddle.device.get_device()
                if cuda_available:
                    device_name = f"NVIDIA GPU ({paddle.device.cuda.get_device_name(0)})"
            except Exception:
                pass

            resp = {
                "status": "ready",
                "engine": "PaddleOCR-VL 1.6 (Local VLM)",
                "pipeline_version": "v1.6",
                "cuda_available": cuda_available,
                "device": device,
                "device_name": device_name,
                "is_gpu": cuda_available and "gpu" in device.lower(),
                "python": sys.version
            }
            self.wfile.write(json.dumps(resp).encode("utf-8"))
        else:
            self.send_response(404)
            self.end_headers()

    def do_POST(self):
        if self.path == "/predict":
            content_length = int(self.headers.get("Content-Length", 0))
            post_data = self.rfile.read(content_length)

            try:
                data = json.loads(post_data.decode("utf-8"))
                file_path = data.get("file_path")
                file_bytes_b64 = data.get("file_bytes_base64")
                filename = data.get("filename", "invoice.png")

                if file_path and os.path.exists(file_path):
                    result = process_document(file_path, filename=filename)
                elif file_bytes_b64:
                    raw_bytes = base64.b64decode(file_bytes_b64)
                    result = process_document(raw_bytes, filename=filename)
                else:
                    result = {"success": False, "error": "No valid file_path or file_bytes_base64 provided."}

                self.send_response(200 if result.get("success") else 400)
                self.send_header("Content-Type", "application/json")
                self.end_headers()
                self.wfile.write(json.dumps(result).encode("utf-8"))

            except Exception as e:
                self.send_response(500)
                self.send_header("Content-Type", "application/json")
                self.end_headers()
                self.wfile.write(json.dumps({"success": False, "error": str(e)}).encode("utf-8"))
        else:
            self.send_response(404)
            self.end_headers()


def run_server(port: int = 8505):
    get_pipeline()
    server_address = ("127.0.0.1", port)
    httpd = ThreadingHTTPServer(server_address, PaddleOCRRequestHandler)
    sys.stderr.write(f"[PaddleOCR-VL Worker] Server listening on http://127.0.0.1:{port}...\n")
    sys.stderr.flush()
    try:
        httpd.serve_forever()
    except KeyboardInterrupt:
        sys.stderr.write("[PaddleOCR-VL Worker] Shutting down...\n")
    finally:
        httpd.server_close()


def main():
    parser = argparse.ArgumentParser(description="PaddleOCR-VL 1.6 Worker Service")
    parser.add_argument("--serve", action="store_true", help="Start HTTP service")
    parser.add_argument("--port", type=int, default=8505, help="HTTP service port (default 8505)")
    parser.add_argument("--predict", type=str, help="Process single document path and output JSON")
    parser.add_argument("--output", type=str, help="Write output JSON to file")
    args = parser.parse_args()

    if args.predict:
        res = process_document(args.predict)
        if args.output:
            with open(args.output, "w", encoding="utf-8") as f:
                json.dump(res, f, indent=2)
        else:
            print(json.dumps(res, indent=2))
    else:
        run_server(args.port)


if __name__ == "__main__":
    main()
